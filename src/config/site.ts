/**
 * Общие сведения о сайте для метаданных и превью ссылок.
 */

export const SITE_NAME = 'Журнал открытой миру';
export const SITE_DESCRIPTION = 'Путевые заметки мирохода Curiosity';

/**
 * Картинка превью по умолчанию — показывается, когда у записи нет своей.
 *
 * Мессенджеры любят горизонтальные 1200×630; здесь вертикальный портрет, так что
 * кадрироваться будет неидеально. Чтобы поменять — положите файл в public/images
 * и поправьте три поля ниже.
 */
export const DEFAULT_OG_IMAGE = {
    url: '/images/ya.jpg',
    width: 727,
    height: 917,
} as const;

/**
 * Картинки для OG-тегов записи.
 *
 * Метаданные страницы перекрывают openGraph из корневого layout целиком, а не
 * сливаются с ним: если страница задаёт свой openGraph и не указывает images,
 * превью останется вообще без картинки. Поэтому дефолт подставляется здесь.
 */
export const ogImages = (url?: string | null, alt: string = SITE_NAME) =>
    url ? [{ url, alt }] : [{ ...DEFAULT_OG_IMAGE, alt }];
