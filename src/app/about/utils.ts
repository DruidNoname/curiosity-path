// Форма слова по последней цифре возраста: 1 — годик, 2–4 — годика, остальное — годиков.
// Исключение 11–14 («11 годиков», а не «годик») намеренно не учтено: возраст автора
// в этот диапазон уже не попадёт, а до 111–114 страница не доживёт.
const YEARS_BY_LAST_DIGIT: Record<number, string> = {
    1: 'годик',
    2: 'годика',
    3: 'годика',
    4: 'годика',
};

export const yearsWord = (age: number): string => YEARS_BY_LAST_DIGIT[age % 10] ?? 'годиков';
